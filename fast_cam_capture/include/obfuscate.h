#define OBF_KEY 0x5A

// Stack XOR Decryptor with volatile barrier to prevent compiler constant propagation
static inline char* obf_dec(const uint8_t* enc, size_t len, char* out_buf) {
    volatile uint8_t vkey = (uint8_t)OBF_KEY;
    for (size_t i = 0; i < len; i++) {
        out_buf[i] = (char)(enc[i] ^ ((vkey + (i & 0x0F)) & 0xFF));
    }
    out_buf[len] = '\0';
    return out_buf;
}

#define DECRYPT_STR(enc_var, buf) obf_dec(enc_var, sizeof(enc_var), buf)

