// Opaque constants (values computed via runtime bitwise shifts instead of literals in .rodata)
static inline uint32_t op_qcarcam_uyvy(void) {
    volatile uint32_t a = 0x7000000;
    volatile uint32_t b = 0x0080000;
    volatile uint32_t c = 0x0000102;
    return a | b | c; // 0x7080102 (QCARCAM_FMT_UYVY_8)
}

static inline uint32_t op_ion_heap_system(void) {
    volatile uint32_t shift = 25;
    return (1u << shift); // 0x2000000
}

static inline uint32_t op_fcam_magic(void) {
    volatile uint32_t f = 'F';
    volatile uint32_t c = 'C';
    volatile uint32_t a = 'A';
    volatile uint32_t m = 'M';
    return (f << 24) | (c << 16) | (a << 8) | m; // 0x4643414D
}

// Anti-debugging & ptrace detection
static inline int check_anti_debug(void) {
    // 1. Check /proc/self/status for TracerPid
    int fd = open("/proc/self/status", O_RDONLY);
    if (fd >= 0) {
        char buf[1024];
        ssize_t n = read(fd, buf, sizeof(buf) - 1);
        close(fd);
        if (n > 0) {
            buf[n] = '\0';
            char* p = strstr(buf, "TracerPid:");
            if (p) {
                p += 10;
                while (*p == ' ' || *p == '\t') p++;
                if (*p > '0' && *p <= '9') {
                    // Tracer detected! Exit immediately.
                    _exit(1);
                }
            }
        }
    }
    return 0;
}
